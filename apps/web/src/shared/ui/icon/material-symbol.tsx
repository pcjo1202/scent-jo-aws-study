/** `DESIGN.md` 「Icons」 표의 아이콘 이름 그대로다. 표와 grep으로 대조된다. */
export type MaterialSymbolName = keyof typeof SYMBOL_PATH

const ICON_SIZE = 24

/**
 * 아이콘은 항상 텍스트와 함께 간다 (`DESIGN.md` 「색 단독 전달 금지」). 그래서 기본이
 * `aria-hidden`이다 — 아이콘 단독 버튼이면 낭독될 이름을 **버튼 쪽 `aria-label`**이 준다.
 *
 * 색은 `currentColor`로 따라간다. 아이콘에 색 역할을 따로 배정하지 않는다.
 */
export function MaterialSymbol({
  name,
  className,
}: {
  name: MaterialSymbolName
  className?: string
}): ReactElement {
  return (
    <svg
      viewBox="0 -960 960 960"
      width={ICON_SIZE}
      height={ICON_SIZE}
      fill="currentColor"
      aria-hidden="true"
      className={`shrink-0 ${className ?? ''}`}
    >
      <path d={SYMBOL_PATH[name]} />
    </svg>
  )
}
